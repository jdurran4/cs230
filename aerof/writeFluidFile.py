"""
Write AERO-F input files (FluidFile) for the quasi-2D embedded cylinder.

One run directory per (Mach, Re) case:  aerof/runs/M<Mach>_Re<Re>/FluidFile
Add more entries to `cases` to set up a sweep.

The run is Dimensional (SI units, like the lab's parachute setup). The freestream
state is set from Mach, Re and a fixed freestream temperature:
    a   = sqrt(gamma R T)         U = Mach a
    mu  = Sutherland(T)           rho = Re mu / (U D)        p = rho R T
Time is specified in convective units D/U so a sweep keeps the same resolution of
the flow physics in every case.

Geometry (D, cylinder center, surface id, domain thickness) is imported from
cylMeshGen.py so the input file always matches the generated mesh.

Usage: edit the parameters below, then run the script (e.g. play in VS Code).
"""
import math
import os

import cylMeshGen as mesh

# ============= User-defined parameters ==============================================
cases = [          # (Mach, Reynolds number based on D); add entries for a sweep
    (1.5, 100),
]

aerofDir = os.path.dirname(os.path.abspath(__file__))
runsDir = os.path.join(aerofDir, 'runs')       # one subdirectory per case

# Paths as seen from inside a run directory (aerof/runs/<case>/)
geometryPrefix = '../../data/SowerF/fluidmodel'           # sower -fluid output
embeddedSurface = '../../sources/embeddedSurface.top'

# Freestream gas
T_inf = 288.15          # freestream temperature [K]
gamma = 1.4             # ratio of specific heats
R_gas = 287.1           # ideal gas constant [J/(kg K)] (AERO-F default; check)
C_suth = 1.458e-6       # Sutherland constant [kg/(m s K^0.5)]      (check vs AERO-F)
S_suth = 110.4          # Sutherland reference temperature [K]      (check vs AERO-F)

# Time, in convective units D/U
dt_conv = 0.02          # time step
tEnd_conv = 300.0       # final time (transient + collection window)
outEvery_conv = 0.5     # time between solution snapshots / restarts

# AMR pre-refinement (done once at startup, then the mesh is fixed)
wallEdge = mesh.D / 50  # min edge length at the cylinder surface
wakeEdge = mesh.D / 10  # min edge length in the shock / wake region
wakeUpstream = 1.5 * mesh.D   # refinement capsule starts this far upstream of center
wakeLength = 10.0 * mesh.D    # ... and extends this far downstream of center
wakeRadius = 1.5 * mesh.D


# ============= Freestream state =====================================================
def freestream(mach, re):
    a = math.sqrt(gamma * R_gas * T_inf)
    U = mach * a
    mu = C_suth * T_inf ** 1.5 / (T_inf + S_suth)
    rho = re * mu / (U * mesh.D)
    p = rho * R_gas * T_inf
    return dict(a=a, U=U, mu=mu, rho=rho, p=p)


def caseName(mach, re):
    return f'M{mach:g}_Re{re:g}'


# ============= FluidFile template ===================================================
def fluidFile(mach, re):
    fs = freestream(mach, re)
    tRef = mesh.D / fs['U']                 # convective time D/U [s]
    dt = dt_conv * tRef
    tEnd = tEnd_conv * tRef
    outEvery = max(1, round(outEvery_conv / dt_conv))   # in time steps
    zMid = mesh.dz / 2

    return f"""\
// AERO-F input: quasi-2D embedded cylinder, generated by writeFluidFile.py
// Case {caseName(mach, re)}: Mach = {mach:g}, Re_D = {re:g}
//   D = {mesh.D:g} m, T = {T_inf:g} K, a = {fs['a']:.6g} m/s, U = {fs['U']:.6g} m/s
//   mu = {fs['mu']:.6g} Pa s, rho = {fs['rho']:.6g} kg/m^3, p = {fs['p']:.6g} Pa
//   D/U = {tRef:.6g} s, dt = {dt_conv:g} D/U, tEnd = {tEnd_conv:g} D/U, output every {outEvery} steps

under Problem {{
    Type      = Unsteady;
    Mode      = Dimensional;
    Prec      = NonPreconditioned;
    Framework = Embedded;
}}

under Input {{
    GeometryPrefix  = "{geometryPrefix}";
    EmbeddedSurface = "{embeddedSurface}";
}}

under AdaptiveMeshRefinement {{

    // Shock standoff and wake region: capsule from upstream of the cylinder, along +x
    under SelectionCriterion[0] {{
        Type = APriori;
        PreRefine = On;
        MinimumEdgeLength = {wakeEdge:.6g};
        NumLevels = 10;
        under RefinementDomain {{
            Type = Capsule;
            under Capsule {{
                Point_x = {mesh.xc - wakeUpstream:.6g};
                Point_y = {mesh.yc:.6g};
                Point_z = {zMid:.6g};
                Normal_x = 1;
                Normal_y = 0;
                Normal_z = 0;
                Radius = {wakeRadius:.6g};
                Length = {wakeUpstream + wakeLength:.6g};
            }}
        }}
    }}

    // Cells cut by the cylinder surface
    under SelectionCriterion[1] {{
        Type = Intersection;
        under PreferredDirection {{
            Type = WallDistanceGradient;
        }}
        under IntersectionCriterion {{
            FaceID = {mesh.ID_CYL};
            Delta = 1e-3;
        }}
        PreRefine = On;
        MinimumEdgeLength = {wallEdge:.6g};
        NumLevels = 15;
    }}

    Mode = NonDimensional;
    BalancingCriterion = ElemMaxMinRatio;
    BalancingThreshold = 1.05;
    BalancingWeight = 2;
    ImbalanceTolerance = 1.0001;
    MaximumRefinementIterations = 1000;
    MaximumCoarseningIterations = 1000;
    ItrFactor = 10000.0;
    UniformityThreshold = 0.90;
    UniformityThresholdType = MinMax;
    MaximumNumberOfElements = 600000000;
    BisectionStrategy = Isotropic;
    ConsistentNumbering = On;
    RecomputeWallDistance = 2;
}}

under Output {{
    under Postpro {{
        PostprocessSides = 1;
        Prefix = "./results/";
        Mach = "Mach";
        Pressure = "Pressure";
        Density = "Density";
        Velocity = "Velocity";
        LiftandDrag = "LiftandDrag";
        Frequency = {outEvery};
    }}
    under Restart {{
        Frequency = {outEvery};
        Prefix = "./references/";
        Solution = "Solution";
        RestartData = "RestartData";
        MeshData = "MeshData";
        EmbeddedPosition = "EmbeddedPosition";
    }}
}}

// Laminar Navier-Stokes (no TurbulenceClosure)
under Equations {{
    Type = NavierStokes;
    under FluidModel[0] {{
        Fluid = PerfectGas;
        under GasModel {{
            SpecificHeatRatio = {gamma:g};
        }}
    }}
    under ViscosityModel {{
        Type = Sutherland;
    }}
}}

under Surfaces {{
    under SurfaceData[{mesh.ID_CYL}] {{
        ComputeForces = True;
        SeparateForces = True;
    }}
}}

// Flow in +x
under BoundaryConditions {{
    under Inlet {{
        Type     = External;
        Mach     = {mach:.10g};
        Density  = {fs['rho']:.10e};
        Pressure = {fs['p']:.10e};
        Alpha    = 0.0;
        Beta     = 0.0;
    }}
    under Wall {{
        Type        = Adiabatic;
        Integration = Full;
    }}
}}

under Space {{
    under NavierStokes {{
        Flux              = HLLC;
        Reconstruction    = Linear;
        AdvectiveOperator = FiniteVolume;
        Limiter           = Venkatakrishnan;
        Gradient          = LeastSquares;
        Dissipation       = SecondOrder;
        Beta              = 0.5;
        Gamma             = 1.0;
    }}
    under Boundaries {{
        Type = StegerWarming;
    }}
}}

under Time {{
    Type = Implicit;
    MaxIts = {math.ceil(tEnd_conv / dt_conv) + 10};
    TimeStep = {dt:.10e};
    MaxTime = {tEnd:.10e};
    under Implicit {{
        Type = RungeKutta2;
        MatrixVectorProduct = FiniteDifference;
        under Newton {{
            MaxIts = 20;
            Eps = 0.001;
            FailSafe = AlwaysOn;
            under LinearSolver {{
                under NavierStokes {{
                    Type = Gmres;
                    MaxIts = 100;
                    KrylovVectors = 100;
                    Eps = 0.01;
                    under Preconditioner {{
                        Type = Ras;
                        Fill = 0;
                    }}
                }}
            }}
        }}
    }}
}}

under EmbeddedFramework {{
    Intersector = PhysBAM;
    RiemannNormal = Structure;
    RotatedRiemann = On;
    FillScopeType = Local;
    FillScope = Always;
}}
"""


# ============= Main =================================================================
if __name__ == '__main__':
    for mach, re in cases:
        runDir = os.path.join(runsDir, caseName(mach, re))
        os.makedirs(runDir, exist_ok=True)
        path = os.path.join(runDir, 'FluidFile')
        with open(path, 'w') as out:
            out.write(fluidFile(mach, re))
        fs = freestream(mach, re)
        print(f'Wrote {os.path.relpath(path, aerofDir)}: U = {fs["U"]:.4g} m/s, '
              f'rho = {fs["rho"]:.4g} kg/m^3, p = {fs["p"]:.4g} Pa, '
              f'dt = {dt_conv * mesh.D / fs["U"]:.4g} s')
